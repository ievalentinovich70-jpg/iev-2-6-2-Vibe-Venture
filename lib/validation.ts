import { z } from "zod";

/** Допустимые стадии проекта */
export const STAGES = ["idea", "prototype", "mvp"] as const;

/**
 * Единая Zod-схема заявки на первичный отбор.
 * Используется и на клиенте (мгновенная валидация в форме),
 * и на сервере (повторная проверка в API-роуте).
 */
export const applicationSchema = z.object({
  founderName: z
    .string()
    .min(2, "Имя должно содержать минимум 2 символа")
    .max(100, "Имя не должно превышать 100 символов"),
  email: z.email("Введите корректный email"),
  companyName: z
    .string()
    .min(2, "Название должно содержать минимум 2 символа")
    .max(100, "Название не должно превышать 100 символов"),
  problem: z
    .string()
    .min(20, "Опишите проблему подробнее — минимум 20 символов")
    .max(2000, "Описание не должно превышать 2000 символов"),
  stage: z.enum(STAGES, "Выберите стадию проекта"),
  pitch: z
    .string()
    .min(20, "Питч должен содержать минимум 20 символов")
    .max(2000, "Питч не должен превышать 2000 символов"),
});

/** Валидированные данные заявки */
export type ApplicationInput = z.infer<typeof applicationSchema>;